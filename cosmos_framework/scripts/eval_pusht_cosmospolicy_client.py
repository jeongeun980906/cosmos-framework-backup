"""Closed-loop PushT eval against the Cosmos-Policy CUSTOM gym_pusht env.

The PushT policy was post-trained on ``PushT-Cosmos-Policy-lerobot`` data, which
was generated by Cosmos-Policy's *forked* gym_pusht env (pymunk_override, custom
visuals) — NOT the upstream PyPI ``gym-pusht``. Rolling out in the upstream env
gives out-of-distribution observations (≈0% success). This client drives the
SAME custom env (matching ``cosmos_policy/.../pusht/run_pusht_eval.py`` exactly:
``visual_opts``, ``success_threshold=0.85``, ``info["coverage"]``, 128px render)
but queries the Cosmos3 action-policy HTTP server instead of the Cosmos-Policy
model.

Run it in an env that has the Cosmos-Policy custom gym_pusht importable, e.g.::

    cd /mnt/ddn/cosmos_policy
    PYTHONPATH=cosmos_policy/experiments/robot/pusht \\
    MUJOCO_GL=egl .venv/bin/python \\
      /mnt/ddn/cosmos-framework/cosmos_framework/scripts/eval_pusht_cosmospolicy_client.py \\
        --server-url http://127.0.0.1:8000 \\
        --visual-config tri_default --num-episodes 50

``--visual-config tri_default`` = triangle agent (the "세모" data). Use ``base``
for the round-agent data, ``tri_color`` for triangle + salmon block, etc. — it
must match the visuals the policy was trained on.
"""

from __future__ import annotations

import argparse
import base64
import datetime
import io
import json
from pathlib import Path

import numpy as np
import requests
from PIL import Image

_PUSHT_PROMPT = "push the T block to the target"
SUCCESS_THRESHOLD = 0.85  # must match Cosmos-Policy run_pusht_eval (env.success_threshold)

# Visual configs copied verbatim from cosmos_policy run_pusht_eval.VISUAL_CONFIGS.
VISUAL_CONFIGS = {
    "base": {},
    "goal_flipped": {"goal_flipped": True},
    "color": {"block_color": "salmon"},
    "tri_color": {"agent_shape": "triangle", "block_color": "salmon"},
    "tri_default": {"agent_shape": "triangle"},
    "tri_goal_flipped": {"agent_shape": "triangle", "goal_flipped": True},
}


def _encode_png_b64(img_hwc_uint8: np.ndarray) -> str:
    buf = io.BytesIO()
    Image.fromarray(img_hwc_uint8).save(buf, format="PNG")
    return base64.b64encode(buf.getvalue()).decode("ascii")


def query_policy(server_url: str, image_hwc_uint8: np.ndarray, image_size: int, agent_pos: np.ndarray) -> np.ndarray:
    payload = {
        "image": _encode_png_b64(image_hwc_uint8),
        "prompt": _PUSHT_PROMPT,
        "domain_name": "pusht",
        "image_size": int(image_size),
        # PushT trained with use_state=True → the server conditions on the current
        # agent position (prepended as action[0]). Without this the policy emits a
        # constant offset. agent_pos is the raw [ax, ay] in [0, 512] (action frame).
        "state": [float(agent_pos[0]), float(agent_pos[1])],
    }
    resp = requests.post(f"{server_url.rstrip('/')}/predict", json=payload, timeout=600)
    resp.raise_for_status()
    data = resp.json()
    action = np.asarray(data.get("action", []), dtype=np.float32)
    if action.ndim == 1:
        action = action[None, :]
    if action.size == 0:
        raise RuntimeError(f"Policy server returned empty action: {data.get('error', '<no error field>')}")
    return action[:, :2]  # [chunk, 2]


def _save_video(frames: list[np.ndarray], path: Path, fps: int = 10) -> None:
    if not frames:
        return
    import imageio

    path.parent.mkdir(parents=True, exist_ok=True)
    imageio.mimwrite(path, frames, fps=fps)


def run(args: argparse.Namespace) -> dict:
    import gymnasium as gym
    import gym_pusht  # noqa: F401  (Cosmos-Policy custom env; registers gym_pusht/PushT-v0)

    if args.visual_config not in VISUAL_CONFIGS:
        raise SystemExit(f"--visual-config must be one of {list(VISUAL_CONFIGS)}")
    visual_opts = dict(VISUAL_CONFIGS[args.visual_config])
    if args.goal_angle is not None:
        # Custom goal orientation in DEGREES (env does np.deg2rad). Overrides the
        # default +45° (tri_default) / -45° (goal_flipped). Matches cosmos_policy
        # run_pusht_eval's --goal_angle. Use to probe goal-rotation generalization.
        visual_opts["goal_angle"] = float(args.goal_angle)

    env = gym.make(
        "gym_pusht/PushT-v0",
        obs_type="pixels_agent_pos",
        render_mode="rgb_array",
        observation_width=args.env_img_res,
        observation_height=args.env_img_res,
    )
    env.success_threshold = SUCCESS_THRESHOLD

    successes = 0
    coverages: list[float] = []
    out_dir = Path(args.out_dir)

    for ep in range(args.num_episodes):
        obs, _ = env.reset(seed=args.seed + ep, options=visual_opts)
        done = False
        t = 0
        coverage = 0.0
        action_queue: list[np.ndarray] = []
        frames: list[np.ndarray] = []

        while not done and t < args.max_steps:
            img = np.ascontiguousarray(obs["pixels"], dtype=np.uint8)
            if len(frames) < args.max_video_frames:
                frames.append(img)

            if not action_queue:
                chunk = query_policy(args.server_url, img, args.image_size, obs["agent_pos"])
                action_queue = list(chunk[: args.num_open_loop_steps])

            action = action_queue.pop(0)
            obs, _reward, terminated, truncated, info = env.step(action.astype(np.float32))
            coverage = float(info.get("coverage", 0.0))
            done = bool(terminated or truncated or info.get("is_success", False) or coverage >= SUCCESS_THRESHOLD)
            t += 1

        success = bool(coverage >= SUCCESS_THRESHOLD or info.get("is_success", False))
        successes += int(success)
        coverages.append(coverage)
        if args.save_videos and (ep < args.save_first_n_videos or not success):
            _save_video(frames, out_dir / f"ep{ep}_{'success' if success else 'fail'}_cov{coverage:.2f}.mp4")
        print(
            f"[pusht/{args.visual_config}] ep {ep+1}/{args.num_episodes} -> {'SUCCESS' if success else 'fail'} "
            f"coverage={coverage:.3f} (running {successes}/{ep+1} = {successes/(ep+1):.1%})",
            flush=True,
        )

    env.close()
    return {
        "visual_config": args.visual_config,
        "num_episodes": args.num_episodes,
        "successes": successes,
        "success_rate": successes / args.num_episodes if args.num_episodes else 0.0,
        "mean_coverage": float(np.mean(coverages)) if coverages else 0.0,
        "success_threshold": SUCCESS_THRESHOLD,
    }


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--server-url", default="http://127.0.0.1:8000")
    ap.add_argument("--visual-config", default="tri_default", help="Must match training visuals (세모=tri_default).")
    ap.add_argument("--goal-angle", type=float, default=None,
                    help="Custom goal orientation in DEGREES (default +45°). e.g. -45 rotates the goal.")
    ap.add_argument("--num-episodes", type=int, default=50)
    ap.add_argument("--num-open-loop-steps", type=int, default=8)
    ap.add_argument("--env-img-res", type=int, default=128, help="Render size (training data native is 128).")
    # image_size = 256 (RESIZE convention). Training now upscales the native 128 frame to
    # 256 in PushTLeRobotDataset._load_video (scene fills the frame, image_size=[256,256,
    # 256,256], no padding). To match, the server must also upscale 128→256: sending
    # image_size=256 makes its resize block do exactly that (then the pad step is a no-op).
    # (The old convention was image_size=128 → reflection-pad 128 into a 256 corner.)
    ap.add_argument("--image-size", type=int, default=256, help="Server image_size = 256 (training upscales 128→256 to fill frame).")
    ap.add_argument("--max-steps", type=int, default=300)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--out-dir", default="/mnt/ddn/outputs/pusht_eval")
    ap.add_argument("--save-videos", action="store_true", default=True)
    ap.add_argument("--no-save-videos", dest="save_videos", action="store_false")
    ap.add_argument("--save-first-n-videos", type=int, default=3)
    ap.add_argument("--max-video-frames", type=int, default=400)
    args = ap.parse_args()

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    stamp = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")

    result = run(args)
    result["timestamp"] = stamp
    result["server_url"] = args.server_url
    report_path = out_dir / f"pusht_eval_{args.visual_config}_{stamp}.json"
    report_path.write_text(json.dumps(result, indent=2))

    print("\n========== PUSHT EVAL SUMMARY (cosmos_policy env) ==========")
    print(f"  visual_config : {result['visual_config']}")
    print(f"  success_rate  : {result['success_rate']:.1%}  ({result['successes']}/{result['num_episodes']})")
    print(f"  mean coverage : {result['mean_coverage']:.3f}  (threshold {SUCCESS_THRESHOLD})")
    print(f"Report: {report_path}")


if __name__ == "__main__":
    main()
