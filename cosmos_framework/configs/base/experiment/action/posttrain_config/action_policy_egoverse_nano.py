"""``action_policy_egoverse_nano`` — Cosmos3-Nano EgoVerse one-shot conditioning-policy SFT.

Unlike the single-clip LIBERO/PushT/DROID recipes, each sample is a **retrieval
pair**: a demonstration clip (``demo``, possibly a different embodiment, same task
class) conditions the generation of a query clip (``query``). The packed sequence
is ``[text | demo_video, query_video | demo_action, query_action]`` (grouped),
with the video-transfer-style shared temporal grid
(``share_vision_temporal_positions=True``) aligning demo↔query frames and action
steps. Demo tokens are fully clean conditioning; the query generates its 1s video
(frame-0 observation clean) + 1s action.

Data comes from ``egoverse_pairs_v9`` (``windows.npz`` + ``pairs.npz``, DYNAMIC
retrieved conditions per query padded to width 20 with ``-1``) over the raw
EgoVerse zarr episodes. v9 retrieval = state/action57 per-window descriptor
(both-hand start-rel pos + 6D rot + action eef delta + hand15, per-window iso)
+ lang_taxonomy canonical-class gate (cross falls back fine→coarse super-group)
+ banded-DTW rerank + threshold handedness penalty; same-emb ≤8, cross-emb
DYNAMIC ``≤7`` (score≤best·1.6). A 150-episode TEST split is held out (loose:
removed as training queries only, still available as demos) — offline eval uses
``egoverse_pairs_v9_test``. The loader is format-agnostic to K (samples one
condition uniformly from the non-``-1`` matches), so v9 is a drop-in.
Actions/states are the egomimic-processed unified vectors (``action57`` for the
human rigs MECKA/scale/aria + the ``mimicdroid`` robocasa demos → domain
``hand_pose``; ``action20`` for the ``eva`` bimanual robot → domain ``eva``),
per-embodiment quantile-normalized via the committed stats JSON and padded to
``max_action_dim=64``. Conditioning text carries the **embodiment label + task + per-emb 0–1 eef speed**
for BOTH demo (source) and query (target), e.g. ``"gr1: <task>. speed: 0.4 | demo mimicdroid speed: 0.8"``.

This trains the generation + multi-domain action heads from the public
``nvidia/Cosmos3-Nano`` base. The multi-segment / shared-grid packing is additive
and gated on ``num_action_items_per_sample`` — the single-clip recipes are
unaffected.

Usage (1 node, N GPU)::

    EGOVERSE_DATA_ROOT=/mnt/ddn/dataset \\
    EGOVERSE_PAIRS_DIR=/mnt/ddn/dataset/egoverse_pairs_v9 \\
    BASE_CHECKPOINT_PATH=<Cosmos3-Nano DCP dir> \\
    WAN_VAE_PATH=<Wan2.2_VAE.pth> \\
    torchrun --nproc_per_node=8 -m cosmos_framework.scripts.train \\
        --sft-toml examples/toml/sft_config/action_policy_egoverse_smoke.toml
"""

